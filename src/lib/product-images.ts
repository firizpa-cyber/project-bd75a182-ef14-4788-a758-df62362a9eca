export function resolveProductImage(src: string): string {
  const oldIndex = oldImages.indexOf(src);
  if (oldIndex !== -1) return PRODUCT_IMAGES[oldIndex]!;
  const localImage = src.match(/^\/(?:src\/assets\/products\/p(\d+)\.jpg|assets\/p(\d+)-[\w-]+\.jpg)$/);
  if (localImage) return PRODUCT_IMAGES[Number(localImage[1] ?? localImage[2]) - 1] ?? src;
  return src;
}
